const columnas = ["Apellidos y nombres completos", "Unidades didácticas que imparte", "Hoja de vida"];
const contenedor = document.querySelector("#directorio-docente");

function crearTabla(programa) {
    const seccion = document.createElement("section");
    seccion.className = "plana-docente-programa";

    const titulo = document.createElement("h2");
    titulo.textContent = programa.nombre;
    seccion.append(titulo);

    const envoltura = document.createElement("div");
    envoltura.className = "plana-docente-tabla-contenedor";

    const tabla = document.createElement("table");
    tabla.className = "plana-docente-tabla";
    tabla.setAttribute("aria-label", `Directorio docente de ${programa.nombre}, periodo lectivo 2026-II`);

    const cabecera = tabla.createTHead().insertRow();
    columnas.forEach((columna) => {
        const th = document.createElement("th");
        th.scope = "col";
        th.textContent = columna;
        cabecera.append(th);
    });

    const cuerpo = tabla.createTBody();
    programa.docentes.forEach((docente) => {
        const fila = cuerpo.insertRow();

        const celdaNombre = fila.insertCell();
        celdaNombre.className = "plana-docente-docente";
        celdaNombre.dataset.label = columnas[0];
        celdaNombre.textContent = docente.nombre;

        const celdaUnidades = fila.insertCell();
        celdaUnidades.className = "plana-docente-unidades";
        celdaUnidades.dataset.label = columnas[1];
        const periodoLectivo = document.createElement("strong");
        periodoLectivo.textContent = periodo;
        celdaUnidades.append(periodoLectivo);

        if (docente.unidades.length > 0) {
            const lista = document.createElement("ul");
            lista.className = "plana-docente-cursos";
            docente.unidades.forEach((unidad) => {
                const item = document.createElement("li");
                item.textContent = unidad;
                lista.append(item);
            });
            celdaUnidades.append(lista);
        }

        const celdaCv = fila.insertCell();
        celdaCv.dataset.label = columnas[2];
        const accionesCv = document.createElement("div");
        accionesCv.className = "plana-docente-cv";

        if (docente.cv) {
            const enlace = document.createElement("a");
            enlace.href = docente.cv;
            enlace.target = "_blank";
            enlace.rel = "noopener noreferrer";
            enlace.textContent = "Ver";
            enlace.setAttribute("aria-label", `Ver hoja de vida: ${docente.nombre}`);
            accionesCv.append(enlace);
        } else {
            const sinCv = document.createElement("span");
            sinCv.className = "plana-docente-sin-cv";
            sinCv.textContent = "No publicada";
            accionesCv.append(sinCv);
        }

        celdaCv.append(accionesCv);
    });

    envoltura.append(tabla);
    seccion.append(envoltura);
    return seccion;
}

if (!contenedor) {
    throw new Error("No se encontró el contenedor del directorio docente.");
}

programas.forEach((programa) => contenedor.append(crearTabla(programa)));
